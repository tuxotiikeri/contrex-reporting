export function translate(text, locale = "fi") {
  if (Array.isArray(text)) return text.map((line) => translate(line, locale));
  return locale === "en" && typeof text === "string" && Object.hasOwn(english, text) ? english[text] : text;
}

// Only display labels change; protocols retain their original keys for grouping.
export function translateProgram(value, locale = "fi") {
  if (locale !== "en" || typeof value !== "string") return value;
  return value.replace(/kons\/kons/g, "con/con").replace(/eks\/eks/g, "ecc/ecc")
    .replace(/\bkons\b/g, "con").replace(/\beks\b/g, "ecc")
    .replace(/isokin\. ballistinen/g, "isokinetic ballistic")
    .replace(/oj\/kouk/g, "ext/flex");
}

// Translate table captions only, preserving measured values and styling.
export function translateTableRows(rows, locale) {
  return rows?.map((row) => {
    const cell = (value) => typeof value === "object" && value !== null
      ? {...value, content: translate(value.content, locale)} : translate(value, locale);
    return Array.isArray(row) ? row.map(cell) : row;
  });
}
